package com.driveden.app.infrastructure.out.persistence.mappers;

import com.driveden.app.domain.cars.dto.carRegisterRequestDTO;
import com.driveden.app.domain.cars.model.vehicleDetailsDomain;
import com.driveden.app.infrastructure.out.persistence.entity.VehicleDetailsEntity;

public class VehicleDetailsMapper {

    public static vehicleDetailsDomain toDomain(VehicleDetailsEntity entity) {
        if (entity == null) {
            return null;
        }
        return new vehicleDetailsDomain(
                entity.getId(), // Include ID in the domain model
                entity.getVehicleId(),
                entity.getFuelTypeId(),
                entity.getTransmissionTypeId(),
                entity.getCurrentKm(),
                entity.getLastTechnicalInspection(),
                entity.getLastSoat()
        );
    }

    public static VehicleDetailsEntity toEntity(vehicleDetailsDomain domain) {
        if (domain == null) {
            return null;
        }
        VehicleDetailsEntity entity = new VehicleDetailsEntity();
        entity.setVehicleId(domain.getVehicleId());
        entity.setFuelTypeId(domain.getFuelTypeId());
        entity.setTransmissionTypeId(domain.getTransmissionTypeId());
        entity.setCurrentKm(domain.getCurrentKm());
        entity.setLastTechnicalInspection(domain.getLastTechnicalInspection());
        entity.setLastSoat(domain.getLastSoat());
        return entity;
    }

    public static vehicleDetailsDomain fromDTOtoDomain(carRegisterRequestDTO dto, Long vehicleId) {
        if (dto == null) {
            return null;
        }
        return new vehicleDetailsDomain(
                null, // ID will be generated by the database
                vehicleId, // Set the vehicle ID
                dto.getFuelId(),
                dto.getTransmissionId(),
                dto.getCurrent_km(),
                dto.getLast_technical_inspection(),
                dto.getLast_soat()
        );
    }

}
