package com.driveden.app.infrastructure.out.persistence.mappers;

import com.driveden.app.domain.cars.dto.carRegisterRequestDTO;
import com.driveden.app.domain.cars.model.vehicleDomain;
import com.driveden.app.infrastructure.out.persistence.entity.VehicleEntity;

public class VehicleMapper {
    
    public static vehicleDomain toDomain(VehicleEntity entity) {
        if (entity == null) {
            return null;
        }
        return new vehicleDomain(
                entity.getId(),
                entity.getBrand(),
                entity.getModel(),
                entity.getYear(),
                entity.getNickName(),
                entity.getVehicleType()
        );
    }

    public static VehicleEntity toEntity(vehicleDomain domain) {
        if (domain == null) {
            return null;
        }
        VehicleEntity entity = new VehicleEntity();
        entity.setId(domain.getId());
        entity.setBrand(domain.getBrand());
        entity.setModel(domain.getModel());
        entity.setYear(domain.getYear());
        entity.setNickName(domain.getNickName());
        entity.setVehicleType(domain.getVehicleType());
        return entity;
    }

    public static vehicleDomain fromDTOtoDomain(carRegisterRequestDTO dto) {
        if (dto == null) {
            return null;
        }
        return new vehicleDomain(
                null, // ID will be generated by the database
                dto.getCarBrand(),
                dto.getCarModel(),
                dto.getCarYear(),
                dto.getNickName(),
                dto.getVehicleType()
        );
    }
}
